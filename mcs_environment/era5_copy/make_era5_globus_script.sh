#!/bin/bash
# Make Globus command-line transfer scripts that copy the ERA5 files needed by the MCS environment extraction from CFS to scratch.
# (Same idea as waccem/era5/scripts/make_era5_3d_filelist_4globus.sh, 2021: one list per month and type, one script per year.)
#
# Usage:   bash make_era5_globus_script.sh YEAR0 YEAR1        e.g.  bash make_era5_globus_script.sh 2007 2007   (a first test year)
#
# What it does (it copies nothing itself):
#   1. checks that every ERA5 source file of the years exists on CFS (stops otherwise);
#   2. leaves out files that are already complete on scratch (same size), so that running it again after a failure only lists what is missing;
#   3. checks that the planned amount fits into your scratch quota;
#   4. writes list_<type>_<YYYYMM> (source paths) and globus_copy_<year>.sh (mkdir + transfer_files.py per month and type) into $WORKDIR (default: here).
# Then:  module load globus-tools ; generate_token.py -s dtn -t dtn --renew ; bash globus_copy_<year>.sh     (README.md in this folder: step-by-step guide)
#
# Settings (environment variables): WORKDIR (where lists and scripts go), ERA5_SRC, ERA5_DST (see era5_common.sh), FORCE=1 (ignore the quota check).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
source "${here}/era5_common.sh"

# Arguments and the folder for the generated files
if [ $# -ne 2 ]; then echo "usage: bash $0 YEAR0 YEAR1"; exit 2; fi
y0=$1
y1=$2
workdir=${WORKDIR:-$PWD}
mkdir -p "${workdir}"

# Counters for the summary
total_bytes=0
n_copy=0
n_skip=0
n_missing=0

# One script per year; the loop below writes its header and then one block per month and type
for y in $(seq "${y0}" "${y1}"); do
    runner="${workdir}/globus_copy_${y}.sh"
    {
        echo "#!/bin/bash"
        echo "# Generated by make_era5_globus_script.sh ${y0} ${y1} on $(date '+%F %T'): copies the ERA5 files of ${y} (plus margin months) from CFS to ${outdir}."
        echo "# Run it after:  module load globus-tools    The first transfer_files.py call asks you to log in to Globus in a browser."
        echo "# Monitor:  check_transfers.py -n 200 -p | tail -30   (it lists the OLDEST tasks first; README.md step 5). Each call below is one Globus task (limit: 3 active, 100 pending per user)."
        echo "# The script stops at the first failed call (a login problem would fail every call the same way). If it fails with"
        echo "# 'AuthAPIError ... 400 Bad Request', renew the helper's tokens:  generate_token.py -s dtn -t dtn --renew   (README.md, step 3), then run it again."
        echo "set -e"
        echo "trap 'set +x; sleep 1; set -x' DEBUG"
    } > "${runner}"
    # The months of this year (with the margin months at the ends of the requested range)
    for ym in $(year_months "${y}" "${y0}" "${y1}"); do
        for type in pl sfc; do
            list="${workdir}/list_${type}_${ym}"
            : > "${list}"
            # Every expected source file: it must exist; it is listed unless the same file (same size) is already on scratch
            while read -r f; do
                if [ ! -f "${f}" ]; then
                    echo "MISSING source file: ${f}"
                    n_missing=$((n_missing + 1))
                    continue
                fi
                size=$(stat -c %s "${f}")
                dst=$(destination_of "${f}" "${type}" "${ym}")
                if [ -f "${dst}" ] && [ "$(stat -c %s "${dst}")" = "${size}" ]; then
                    n_skip=$((n_skip + 1))
                    continue
                fi
                echo "${f}" >> "${list}"
                total_bytes=$((total_bytes + size))
                n_copy=$((n_copy + 1))
            done < <(expected_files "${type}" "${ym}")
            # A transfer task is only written when the month still has something to copy
            if [ -s "${list}" ]; then
                odir="${outdir}/e5.oper.an.${type}/${ym}/"
                echo "mkdir -p ${odir}" >> "${runner}"
                echo "transfer_files.py -s dtn -t dtn -d ${odir} -i ${list} -p" >> "${runner}"
            else
                rm -f "${list}"
            fi
        done
    done
    echo "wrote ${runner} ($(grep -c '^transfer_files.py' "${runner}") transfer tasks)"
done

# Stop when source files are missing: the copy would be incomplete without anybody noticing
if [ "${n_missing}" -gt 0 ]; then
    echo "ERROR: ${n_missing} source files are missing on CFS; fix the years or the names before running the scripts"
    exit 1
fi

# Summary and the quota check (lfs quota -q prints: filesystem, used kB, quota kB, limit kB, grace, files, ...)
echo "files to copy: ${n_copy}, already complete on scratch: ${n_skip}, planned size: $(awk -v b="${total_bytes}" 'BEGIN {printf "%.2f TB", b/1e12}')"
quota_line=$(lfs quota -q -u "${USER}" /pscratch 2>/dev/null | tr '\n' ' ' | awk '{print $2, $3}')
used_kb=${quota_line%% *}
quota_kb=${quota_line##* }
if [[ "${used_kb}" =~ ^[0-9]+$ && "${quota_kb}" =~ ^[0-9]+$ && "${quota_kb}" -gt 0 ]]; then
    free_kb=$((quota_kb - used_kb))
    echo "scratch quota of ${USER}: used $(awk -v k="${used_kb}" 'BEGIN {printf "%.1f", k*1024/1e12}') TB of $(awk -v k="${quota_kb}" 'BEGIN {printf "%.1f", k*1024/1e12}') TB"
    if [ $((total_bytes / 1024 * 105 / 100)) -gt "${free_kb}" ] && [ "${FORCE:-0}" != "1" ]; then
        echo "ERROR: the planned copy does not fit into the free quota (FORCE=1 ignores this check); copy fewer years"
        exit 1
    fi
else
    echo "WARNING: could not read the quota with 'lfs quota'; check it yourself before running the scripts"
fi
